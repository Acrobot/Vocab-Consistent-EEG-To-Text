import pandas as pd
import argparse
import sys
import os

def main():
    parser = argparse.ArgumentParser(description="Calculate statistics from aggregated CSV results.")
    parser.add_argument('--input_csv', '-i', required=True, help="Path to input CSV file generated by process_to_csv.py")
    parser.add_argument('--output_md', '-o', help="Path to output Markdown report (optional, prints to stdout if not set)")
    args = parser.parse_args()

    input_csv = args.input_csv
    
    if not os.path.exists(input_csv):
        print(f"Error: Input file {input_csv} does not exist.")
        sys.exit(1)

    try:
        df = pd.read_csv(input_csv)
    except Exception as e:
        print(f"Error reading CSV: {e}")
        sys.exit(1)

    if 'Input' not in df.columns:
        print("Error: CSV must contain an 'Input' column for grouping (e.g. EEG, noise).")
        sys.exit(1)
        
    # Identification of metric columns (numeric columns that are not Subject/Input/File)
    exclude_cols = ['Subject', 'Input', 'File', 'Unnamed: 0']
    metric_cols = [c for c in df.columns if c not in exclude_cols and pd.api.types.is_numeric_dtype(df[c])]

    if not metric_cols:
        print("No numeric metric columns found.")
        sys.exit(0)

    # Group by Input and calculate stats
    grouped = df.groupby('Input')[metric_cols].agg(['mean', 'std', 'count']).transpose()
    
    # Prepare Markdown Output
    lines = []
    lines.append(f"# Analysis Report")
    lines.append(f"**Source Data**: `{input_csv}`\n")
    
    unique_inputs = df['Input'].unique()
    
    for input_type in unique_inputs:
        lines.append(f"## Input Type: {input_type} (N={len(df[df['Input']==input_type])})")
        lines.append("| Metric | Mean | Std Dev |")
        lines.append("|---|---|---|")
        
        # Determine subset for this input (to handle potential NaN columns if distinct metrics per input)
        subset = df[df['Input'] == input_type][metric_cols]
        stats = subset.describe().transpose()
        
        for metric in metric_cols:
            if metric in stats.index:
                mean_val = stats.loc[metric, 'mean']
                std_val = stats.loc[metric, 'std']
                lines.append(f"| **{metric}** | {mean_val:.4f} | {std_val:.4f} |")
        lines.append("\n")

    # Comparison Table (if both EEG and noise exist)
    if 'EEG' in unique_inputs:
        lines.append("## Comparative Analysis (EEG vs Others)")
        eeg_means = df[df['Input'] == 'EEG'][metric_cols].mean()
        
        for other_input in [u for u in unique_inputs if u != 'EEG']:
            lines.append(f"### EEG vs {other_input}")
            lines.append("| Metric | EEG Mean | {0} Mean | Delta (EEG - {0}) |".format(other_input))
            lines.append("|---|---|---|---|")
            
            other_means = df[df['Input'] == other_input][metric_cols].mean()
            
            for metric in metric_cols:
                val_eeg = eeg_means.get(metric, 0)
                val_other = other_means.get(metric, 0)
                delta = val_eeg - val_other
                lines.append(f"| {metric} | {val_eeg:.4f} | {val_other:.4f} | {delta:.4f} |")
            lines.append("\n")


    final_output = "\n".join(lines)
    
    if args.output_md:
        with open(args.output_md, 'w') as f:
            f.write(final_output)
        print(f"Report written to {args.output_md}")
    else:
        print(final_output)

if __name__ == "__main__":
    main()
