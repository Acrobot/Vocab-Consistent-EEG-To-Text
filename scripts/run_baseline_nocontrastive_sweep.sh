#!/bin/bash
# Run the WandB Sweep for the vocab-consistent baseline (BrainTranslatorBaseline,
# no contrastive penalty). This script creates the sweep on wandb and then
# launches the agent for N_TRIALS trials.
#
# Architecture:        BrainTranslatorBaseline
# Split:               vocabulary-consistent (the same one as the contrastive headline)
# Subjects:            ALL (30-subject cohort)
# Contrastive penalty: disabled (lambda = 0, the default)
# Trials:              8 (Bayesian; configurable below)
#
# Expected resources:
#   - GPU time: ~8 hours (~1h per trial on RTX 4080)
#   - Disk:     ~14 GB total (`best/` only; `last/` auto-deleted per trial)
#
# Output:
#   - Checkpoints: ./checkpoints/decoding/sweep_baseline_nocontrastive/<run_id>/best/...
#   - Wandb runs:  project Vocab-Consistent-EEG-To-Text, sweep <auto-generated id>
#
# Safety: this script does NOT touch any existing checkpoint, config, or eval result.

set -e

WANDB_EXE="${WANDB_EXE:-wandb}"
PROJECT="${WANDB_PROJECT:-Vocab-Consistent-EEG-To-Text}"
ENTITY="${WANDB_ENTITY:?Set WANDB_ENTITY to your W&B account or team}"
N_TRIALS=8
CONFIG_YAML="scripts/sweep_baseline_nocontrastive_config.yaml"

cd "$(dirname "${BASH_SOURCE[0]}")/.."

echo "=========================================="
echo "Vocab-consistent baseline sweep"
echo "  project: $PROJECT"
echo "  trials:  $N_TRIALS"
echo "  config:  $CONFIG_YAML"
echo "=========================================="

# Step 1: create the sweep on wandb
echo ""
echo "Creating WandB sweep..."
SWEEP_OUTPUT=$("$WANDB_EXE" sweep --project "$PROJECT" "$CONFIG_YAML" 2>&1)
echo "$SWEEP_OUTPUT"

# Parse the sweep ID — wandb prints "Created sweep with ID: <id>"
SWEEP_ID=$(echo "$SWEEP_OUTPUT" | grep -oE "Creat(ing|ed) sweep with ID: [a-zA-Z0-9]+" | awk '{print $NF}' | head -1)

if [ -z "$SWEEP_ID" ]; then
    echo ""
    echo "ERROR: Could not parse sweep ID from output above. Sweep may not have been created."
    exit 1
fi

echo ""
echo "Sweep created: $ENTITY/$PROJECT/$SWEEP_ID"
echo "View at: https://wandb.ai/$ENTITY/$PROJECT/sweeps/$SWEEP_ID"
echo ""

# Step 2: run the agent for N_TRIALS trials
echo "Launching agent ($N_TRIALS trials)..."
"$WANDB_EXE" agent "$ENTITY/$PROJECT/$SWEEP_ID" --count "$N_TRIALS"

echo ""
echo "=========================================="
echo "Sweep complete."
echo "  sweep ID: $SWEEP_ID"
echo "  view:     https://wandb.ai/$ENTITY/$PROJECT/sweeps/$SWEEP_ID"
echo "=========================================="
